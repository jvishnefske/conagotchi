//! Pixel-art frames of the pet cat.
//!
//! Each [`Frame`] is 32 rows of 32 characters, one character per logical
//! pixel, so the art stays readable and diffable. The palette characters are
//! listed in [`PALETTE`]; `'.'` is transparent. The cat faces right in the
//! side views; the renderer mirrors it when it walks left.
//!
//! The per-mode sequences ([`IDLE`], [`WALK`], [`EAT`], [`PLAY`], [`SLEEP`])
//! reference frames, so a picture can appear more than once in a cycle
//! without being stored twice.

/// One 32x32 frame, top row first.
pub type Frame = [&'static str; 32];

/// Characters a frame may use: transparent, outline, fur, stripes, pink,
/// white and accent (bowl, ball, "z").
pub const PALETTE: [u8; 7] = *b".ofspwa";

